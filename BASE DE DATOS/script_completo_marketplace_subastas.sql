-- ----------------------------------------------------------------------------
--  TABLAS DE GEOGRAFIA
-- ----------------------------------------------------------------------------

CREATE TABLE PAIS (
    ID_PAIS NUMBER NOT NULL,
    NOMBRE VARCHAR2(100) NOT NULL,
    CONSTRAINT PK_PAIS PRIMARY KEY (ID_PAIS)
);

CREATE TABLE REGION (
    ID_REGION NUMBER NOT NULL,
    NOMBRE VARCHAR2(100) NOT NULL,
    ID_PAIS NUMBER NOT NULL,
    CONSTRAINT PK_REGION PRIMARY KEY (ID_REGION),
    CONSTRAINT FK_REGION_PAIS FOREIGN KEY (ID_PAIS) REFERENCES PAIS(ID_PAIS)
);

CREATE TABLE CIUDAD (
    ID_CIUDAD NUMBER NOT NULL,
    NOMBRE VARCHAR2(100) NOT NULL,
    ID_REGION NUMBER NOT NULL,
    CONSTRAINT PK_CIUDAD PRIMARY KEY (ID_CIUDAD),
    CONSTRAINT FK_CIUDAD_REGION FOREIGN KEY (ID_REGION) REFERENCES REGION(ID_REGION)
);

CREATE TABLE COMUNA (
    ID_COMUNA NUMBER NOT NULL,
    NOMBRE VARCHAR2(100) NOT NULL,
    ID_CIUDAD NUMBER NOT NULL,
    CONSTRAINT PK_COMUNA PRIMARY KEY (ID_COMUNA),
    CONSTRAINT FK_COMUNA_CIUDAD FOREIGN KEY (ID_CIUDAD) REFERENCES CIUDAD(ID_CIUDAD)
);

-- ----------------------------------------------------------------------------
--  TABLAS MENORES ESCENCIALES
-- ----------------------------------------------------------------------------

CREATE TABLE CATEGORIA (
    ID_CATEGORIA NUMBER NOT NULL,
    NOMBRE VARCHAR2(100) NOT NULL,
    CONSTRAINT PK_CATEGORIA PRIMARY KEY (ID_CATEGORIA)
);

CREATE TABLE ESTADO_PRODUCTO (
    ID_ESTADO_PRODUCTO NUMBER NOT NULL,
    NOMBRE VARCHAR2(100) NOT NULL,
    CONSTRAINT PK_ESTADO_PRODUCTO PRIMARY KEY (ID_ESTADO_PRODUCTO)
);

CREATE TABLE ESTADO_VENTA (
    ID_ESTADO_VENTA NUMBER NOT NULL,
    NOMBRE VARCHAR2(100) NOT NULL,
    CONSTRAINT PK_ESTADO_VENTA PRIMARY KEY (ID_ESTADO_VENTA)
);

-- ----------------------------------------------------------------------------
--  TABLA USUARIO
-- ----------------------------------------------------------------------------

CREATE TABLE USUARIO (
    ID_USUARIO NUMBER NOT NULL,
    RUT VARCHAR2(12) NOT NULL,
    DV VARCHAR2(1) NOT NULL,
    PNOMBRE VARCHAR2(50) NOT NULL,
    SNOMBRE VARCHAR2(50),
    TNOMBRE VARCHAR2(50),
    PAPELLIDO VARCHAR2(50) NOT NULL,
    SAPELLIDO VARCHAR2(50),
    ESTRELLAS NUMBER(2, 1),
    ID_COMUNA NUMBER NOT NULL,
    CONSTRAINT PK_USUARIO PRIMARY KEY (ID_USUARIO),
    CONSTRAINT FK_USUARIO_COMUNA FOREIGN KEY (ID_COMUNA) REFERENCES COMUNA(ID_COMUNA)
);

-- ----------------------------------------------------------------------------
--  TABLA PRODUCTO
-- ----------------------------------------------------------------------------

CREATE TABLE PRODUCTO (
    ID_PRODUCTO NUMBER NOT NULL,
    NOMBRE VARCHAR2(200) NOT NULL,
    DESCRIPCION VARCHAR2(500),
    PRECIO NUMBER(12, 2) NOT NULL,
    PRECIO_DESCUENTO NUMBER(12, 2),
    ID_ESTADO_VENTA NUMBER NOT NULL,
    ID_ESTADO_PRODUCTO NUMBER NOT NULL,
    ID_USUARIO_VENDEDOR NUMBER NOT NULL,
    FECHA_PUBLICACION DATE NOT NULL,
    ID_CATEGORIA NUMBER NOT NULL,
    CONSTRAINT PK_PRODUCTO PRIMARY KEY (ID_PRODUCTO),
    CONSTRAINT FK_PRODUCTO_CATEGORIA FOREIGN KEY (ID_CATEGORIA) REFERENCES CATEGORIA(ID_CATEGORIA),
    CONSTRAINT FK_PRODUCTO_ESTADO_PRODUCTO FOREIGN KEY (ID_ESTADO_PRODUCTO) REFERENCES ESTADO_PRODUCTO(ID_ESTADO_PRODUCTO),
    CONSTRAINT FK_PRODUCTO_ESTADO_VENTA FOREIGN KEY (ID_ESTADO_VENTA) REFERENCES ESTADO_VENTA(ID_ESTADO_VENTA),
    CONSTRAINT FK_PRODUCTO_VENDEDOR FOREIGN KEY (ID_USUARIO_VENDEDOR) REFERENCES USUARIO(ID_USUARIO)
);

-- ----------------------------------------------------------------------------
--  TABLAS DE SUBASTAS Y OFERTAS
-- ----------------------------------------------------------------------------

CREATE TABLE SUBASTA (
    ID_SUBASTA NUMBER NOT NULL,
    NOMBRE VARCHAR2(200) NOT NULL,
    DESCRIPCION VARCHAR2(500),
    ID_PRODUCTO NUMBER NOT NULL,
    PRECIO_MINIMO NUMBER(12, 2) NOT NULL,
    FECHA_PUBLICACION DATE NOT NULL,
    FECHA_FINALIZACION DATE NOT NULL,
    ID_ESTADO_VENTA NUMBER NOT NULL,
    ID_USUARIO NUMBER NOT NULL,
    CONSTRAINT PK_SUBASTA PRIMARY KEY (ID_SUBASTA),
    CONSTRAINT FK_SUBASTA_ESTADO_VENTA FOREIGN KEY (ID_ESTADO_VENTA) REFERENCES ESTADO_VENTA(ID_ESTADO_VENTA),
    CONSTRAINT FK_SUBASTA_PRODUCTO FOREIGN KEY (ID_PRODUCTO) REFERENCES PRODUCTO(ID_PRODUCTO),
    CONSTRAINT FK_SUBASTA_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO(ID_USUARIO)
);

CREATE TABLE OFERTA (
    ID_OFERTA      NUMBER NOT NULL,
    ID_SUBASTA     NUMBER NOT NULL,
    ID_USUARIO     NUMBER NOT NULL,
    MONTO          NUMBER(12) NOT NULL, 
    FECHA_OFERTA   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL, -- Marca exacta de tiempo para diferenciar si es que dos personas ofertan al mismo tiempo osi
    COMENTARIO     VARCHAR2(500),
    CONSTRAINT PK_OFERTA PRIMARY KEY (ID_OFERTA),
    CONSTRAINT FK_OFERTA_SUBASTA FOREIGN KEY (ID_SUBASTA) REFERENCES SUBASTA(ID_SUBASTA),
    CONSTRAINT FK_OFERTA_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO(ID_USUARIO),
    CONSTRAINT CK_MONTO_POSITIVO CHECK (MONTO > 0)
);

-- ----------------------------------------------------------------------------
--  TABLA TRANSACCION_SUBASTA
-- ----------------------------------------------------------------------------

CREATE TABLE TRANSACCION_SUBASTA (
    ID_TRANSACCION       NUMBER NOT NULL,
    ID_SUBASTA           NUMBER NOT NULL UNIQUE,
    ID_PRODUCTO          NUMBER NOT NULL,
    ID_USUARIO_GANADOR   NUMBER NOT NULL,
    ID_USUARIO_VENDEDOR  NUMBER NOT NULL,
    MONTO_FINAL          NUMBER(12) NOT NULL,
    COMISION_PLATAFORMA  NUMBER(12) NOT NULL,
    FECHA_CIERRE         DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_TRANSACCION_SUBASTA PRIMARY KEY (ID_TRANSACCION),
    CONSTRAINT FK_TRANS_SUBASTA FOREIGN KEY (ID_SUBASTA) REFERENCES SUBASTA(ID_SUBASTA),
    CONSTRAINT FK_TRANS_PRODUCTO FOREIGN KEY (ID_PRODUCTO) REFERENCES PRODUCTO(ID_PRODUCTO),
    CONSTRAINT FK_TRANS_GANADOR FOREIGN KEY (ID_USUARIO_GANADOR) REFERENCES USUARIO(ID_USUARIO),
    CONSTRAINT FK_TRANS_VENDEDOR FOREIGN KEY (ID_USUARIO_VENDEDOR) REFERENCES USUARIO(ID_USUARIO)
);

-- ----------------------------------------------------------------------------
--  NUEVAS TABLAS: IMAGENES Y MENSAJES
-- ----------------------------------------------------------------------------

CREATE TABLE IMAGENES (
    ID_IMAGEN NUMBER NOT NULL,
    URL_IMAGEN VARCHAR2(500) NOT NULL,
    ES_PRINCIPAL NUMBER(1) DEFAULT 0 CHECK (ES_PRINCIPAL IN (0, 1)),
    FECHA_SUBIDA DATE DEFAULT SYSDATE NOT NULL,
    ID_PRODUCTO NUMBER NOT NULL,
    CONSTRAINT PK_IMAGENES PRIMARY KEY (ID_IMAGEN),
    CONSTRAINT FK_IMAGENES_PRODUCTO FOREIGN KEY (ID_PRODUCTO) REFERENCES PRODUCTO(ID_PRODUCTO) ON DELETE CASCADE
);

CREATE TABLE MENSAJES (
    ID_MENSAJE          NUMBER NOT NULL,
    CONTENIDO           VARCHAR2(1000) NOT NULL,
    FECHA_ENVIO         TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    LEIDO               NUMBER(1) DEFAULT 0 CHECK (LEIDO IN (0, 1)),
    ID_USUARIO_EMISOR   NUMBER NOT NULL,
    ID_USUARIO_RECEPTOR NUMBER NOT NULL,
    ID_PRODUCTO         NUMBER,
    CONSTRAINT PK_MENSAJES PRIMARY KEY (ID_MENSAJE),
    CONSTRAINT FK_MENSAJES_EMISOR FOREIGN KEY (ID_USUARIO_EMISOR) REFERENCES USUARIO(ID_USUARIO),
    CONSTRAINT FK_MENSAJES_RECEPTOR FOREIGN KEY (ID_USUARIO_RECEPTOR) REFERENCES USUARIO(ID_USUARIO),
    CONSTRAINT FK_MENSAJES_PRODUCTO FOREIGN KEY (ID_PRODUCTO) REFERENCES PRODUCTO(ID_PRODUCTO) ON DELETE SET NULL,
    CONSTRAINT CK_MENSAJE_USUARIOS_DISTINTOS CHECK (ID_USUARIO_EMISOR <> ID_USUARIO_RECEPTOR)
);

